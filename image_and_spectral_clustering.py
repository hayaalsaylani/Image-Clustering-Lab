import numpy as np
import matplotlib.pyplot as plt

from sklearn.cluster import spectral_clustering
from sklearn.feature_extraction import image as sk_image

from skimage import data
from skimage.transform import rescale
from skimage.filters import gaussian

# Step 1: Load the original coins image
image = data.coins()

print("Image shape:", image.shape)

# Step 2: Display the image before Spectral Clustering
plt.figure(figsize=(8, 6))

plt.imshow(image, cmap="gray")
plt.title("Coins Image Before Spectral Clustering")
plt.axis("off")

plt.savefig("spectral_image_before.png")
plt.show()

# Step 3: Smooth the image
smoothed_image = gaussian(image, sigma=2)

# Resize the image to 20% of its original dimensions
small_image = rescale(
    smoothed_image,
    0.2,
    anti_aliasing=True
)

print("Original image shape:", image.shape)
print("Smaller image shape:", small_image.shape)

# Create a graph of neighboring pixels
graph = sk_image.img_to_graph(small_image)

# Adjust the graph connection weights
graph.data = np.exp(
    -10 * graph.data / graph.data.std()
)

print("Graph created successfully.")
print("Number of graph connections:", graph.nnz)

# Apply Spectral Clustering
labels = spectral_clustering(
    graph,
    n_clusters=25,
    assign_labels="discretize",
    random_state=42
)

# Reshape the labels to match the smaller image
segmented_image = labels.reshape(small_image.shape)

print("Spectral Clustering completed.")
print("Segmented image shape:", segmented_image.shape)
print("Number of clusters:", len(np.unique(labels)))

# Step 4: Display the image after Spectral Clustering
plt.figure(figsize=(8, 6))

plt.imshow(segmented_image, cmap="nipy_spectral")
plt.title("Coins Image After Spectral Clustering (25 Clusters)")
plt.axis("off")

plt.savefig("spectral_image_after.png")
plt.show()